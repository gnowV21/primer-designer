#!/usr/bin/env python3
"""
build_validation_report.py — human-readable Markdown report of the deterministic
ground-truth validation (VALIDATION_PLAN.md), one row per benchmarked miRNA.

Reads validation/results.json (produced by validate_primers.py) and
validation/reference_mirnas.json (for role/citation text) — never re-derives or
invents numbers; every value is copied from those two generated/curated files.
Writes validation/VALIDATION_REPORT.md. Regenerate after any validate_primers.py
or reference_mirnas.json change — do not hand-edit the output.
"""
import json
import os

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")


def load(path):
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        return json.load(f)


def main():
    results = load("validation/results.json")
    ref = {e["id"]: e for e in load("validation/reference_mirnas.json")["mirnas"]}

    targets = results["targets"]
    mirnas = [t for t in targets if t.get("rt_overhang_expected") is not None]
    edges = [t for t in targets if t.get("edge_expected") is not None]

    lines = []
    lines.append("# VALIDATION_REPORT.md — per-miRNA ground-truth validation results")
    lines.append("")
    lines.append(f"Generated by `backend/scripts/build_validation_report.py` from "
                  f"`validation/results.json` (run {results['run_date']}). "
                  f"Do not hand-edit — rerun `validate_primers.py` then this script.")
    lines.append("")
    lines.append(f"**Summary: {results['checks_passed']}/{results['checks_total']} checks "
                  f"passed ({results['success_rate']*100:.1f}%)** across "
                  f"{len(mirnas)} miRNAs + {len(edges)} edge cases. "
                  "Methodology and acceptance criteria: [VALIDATION_PLAN.md](VALIDATION_PLAN.md).")
    lines.append("")

    # ── Section 1: deterministic + plausibility + specificity, per miRNA ──
    lines.append("## 1. Deterministic ground-truth checks (groups A/B/C)")
    lines.append("")
    lines.append("Every value below is recomputed independently from the exact sequence "
                  "the tool used (`metadata.mirna_sequence`), not hand-entered — see "
                  "VALIDATION_PLAN.md §2.")
    lines.append("")
    lines.append("| miRNA | Checks | RT overhang (expected = actual) | Fwd Tm °C | Fwd GC% | "
                  "Amplicon bp | let-7 siblings flagged |")
    lines.append("|---|---|---|---|---|---|---|")
    for t in mirnas:
        mid = t["target"]
        sib = t.get("siblings_flagged") or "—"
        if len(sib) > 60:
            sib = sib[:57] + "..."
        lines.append(
            f"| {mid} | {t['checks_pass']}/{t['checks_total']} PASS | "
            f"`{t['rt_overhang_expected']}` = `{t['rt_overhang_actual']}` | "
            f"{t['forward_tm_c']} | {t['forward_gc_pct']} | {t['amplicon_bp']} | {sib} |"
        )
    lines.append("")

    # ── Section 2: published (journal/thesis) primer comparison ──
    lines.append("## 2. Tool primer vs. published primer (journal / conference / thesis)")
    lines.append("")
    lines.append("Only miRNAs `reference_mirnas.json` cites a real external source for. "
                  "Full side-by-side primer sequences for all 55 benchmarked miRNAs: "
                  "[benchmark/primer_benchmark_export.csv](../benchmark/primer_benchmark_export.csv).")
    lines.append("")
    lines.append("| miRNA | RT exact match | Overhang match | Forward specific-region agrees | Source |")
    lines.append("|---|---|---|---|---|")
    for t in mirnas:
        mid = t["target"]
        has_pub = any(t.get(k) for k in
                      ("published_rt_match", "published_forward_specific_shared")) or ref[mid].get("published_rt_overhang")
        if not has_pub:
            continue
        src = ref[mid].get("published_source", "")
        src_short = src.split(".")[0][:70] + ("…" if len(src) > 70 else "")
        lines.append(
            f"| {mid} | {t.get('published_rt_match') or '—'} | "
            f"{t.get('published_rt_overhang_match') or '—'} | "
            f"{t.get('published_forward_specific_shared') or '—'} | {src_short} |"
        )
    lines.append("")
    lines.append("Full citations (author, venue, year, DOI/PMID where indexed) are in "
                  "`validation/reference_mirnas.json` next to each miRNA entry.")
    lines.append("")

    # ── Section 3: edge cases ──
    lines.append("## 3. Edge cases (group D)")
    lines.append("")
    lines.append("| Label | Expected code | Found code(s) | Result |")
    lines.append("|---|---|---|---|")
    for t in edges:
        lines.append(f"| {t['target']} | {t['edge_expected']} | {t['edge_found']} | "
                      f"{t['checks_pass']}/{t['checks_total']} PASS |")
    lines.append("")

    lines.append("## 4. Caveats")
    lines.append("")
    lines.append("- hsa-miR-16-5p is matched against Chen, Bosmajian & Woo 2024 (*Biol Methods "
                  "Protoc*, PMID 38783988); the lab's 2020 Vietnamese conference paper is cited "
                  "as a second, non-PubMed-indexed source.")
    lines.append("- hsa-miR-155-5p: the published RT overhangs (Czimmerer 2013, Yang 2014) target "
                  "the older 23-nt annotation; miRBase v22 gives 24 nt, so only the forward core "
                  "is scored — see the note in reference_mirnas.json.")
    lines.append("- Chen 2005 (the original stem-loop paper): 6 RT primers are byte-identical to the "
                  "tool. For miR-7, miR-10b, miR-20a, let-7d and let-7e the paper used the 2005 "
                  "mature sequences, whose 3' ends miRBase has since changed; let-7a used a 5-nt "
                  "overhang; let-7b's listed overhang is not complementary to let-7b (source typo). "
                  "Those RT primers are not scored; their forward cores are.")
    lines.append("- 4 entries (miR-125b-5p, miR-9-3p, miR-221-3p, miR-222-3p) cite **unpublished "
                  "lab-internal bachelor theses** — recorded as such, not presented as "
                  "peer-reviewed sources.")
    lines.append("- This report is distinct from, and does not use, the miR-16 \"exp 220826\" "
                  "wet-lab case study in AUDIT_REPORT.md §3, which is explicitly not ground truth.")
    lines.append("- The 50-miRNA panel in `benchmark/panel.json` has no external tool configured "
                  "(`MIRPRIMER_TOOL` unset) — those rows in primer_benchmark_export.csv show this "
                  "tool's own output only, no published-primer columns.")
    lines.append("")

    out = os.path.join(ROOT, "validation", "VALIDATION_REPORT.md")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
