"""
benchmark/run_benchmark.py — Phase 6 §C.2

Calls /api/design for every miRNA in panel.json, collects primer metrics,
and writes benchmark/compare_tools.md.

Usage:
    cd benchmark
    python run_benchmark.py [--base-url http://localhost:5000] [--out compare_tools.md]

Dependencies: requests (already in backend/requirements.txt; run from backend env)
No external tools (miRprimer/miPrimer) are required — tool comparison columns
are populated only if MIRPRIMER_TOOL env-var points to a callable executable.

LIMITATION: Published paper efficiencies are NOT valid comparison targets.
Calibration data must be self-generated wet-lab efficiencies on tool-designed
primers (including failures). See calibration/calibration_data_requirement.md.
"""
import argparse
import json
import os
import subprocess
import sys
import time
from pathlib import Path

import requests

# ── Default constants ────────────────────────────────────────────────────────
BASE_URL   = "http://localhost:5000"
PANEL_FILE = Path(__file__).parent / "panel.json"
OUT_FILE   = Path(__file__).parent / "compare_tools.md"

DEFAULT_PARAMS = {
    "na_conc":          50.0,
    "mg_conc":          3.0,
    "dntp_conc":        0.2,
    "primer_conc":      0.25,
    "gc_min":           40,
    "gc_max":           65,
    "tm_min":           58,
    "tm_max":           63,
    "amplicon_min":     90,
    "amplicon_max":     130,
    "top_n":            3,
    "signalMethod":     "sybr",
}

# /api/design expects: {"sequence": {"matureSequence": "<DNA>", "mirnaId": "<id>"}, ...params}
# See routes/design.py line 37: data.get("sequence", {}).get("matureSequence", "")


# ── Helpers ──────────────────────────────────────────────────────────────────

def _rna_to_dna(seq: str) -> str:
    return seq.upper().replace("U", "T")


def _call_design(base_url: str, mirna_seq: str, mirna_id: str = "") -> dict | None:
    """Call /api/design with SYBR defaults; return parsed JSON or None."""
    # /api/design expects RNA (U not T); panel.json stores RNA sequences
    payload = {
        **DEFAULT_PARAMS,
        "sequence": {
            "matureSequence": mirna_seq.upper(),
            "mirnaId": mirna_id,
        },
    }
    try:
        resp = requests.post(f"{base_url}/api/design", json=payload, timeout=30)
        if resp.status_code == 200:
            return resp.json()
        return {"error": f"HTTP {resp.status_code}: {resp.text[:120]}"}
    except Exception as exc:
        return {"error": str(exc)}


def _call_mirprimer(mirprimer_bin: str, mirna_seq: str) -> dict | None:
    """Call external miRprimer binary if configured; return dict or None."""
    if not mirprimer_bin:
        return None
    try:
        result = subprocess.run(
            [mirprimer_bin, "--seq", _rna_to_dna(mirna_seq)],
            capture_output=True, text=True, timeout=60,
        )
        if result.returncode == 0:
            return {"stdout": result.stdout.strip()}
        return {"error": result.stderr.strip()[:120]}
    except Exception as exc:
        return {"error": str(exc)}


def _extract_metrics(result: dict) -> dict:
    """Pull forward/RT Tm, GC, dimer risk from /api/design response.

    /api/design response shape (routes/design.py):
      top3[i]: { tm_full, tm_binding, gc_percent, sequence, total_score,
                 heterodimer_checks: {any_high_risk, ...}, ... }
      stemloop_rt: { tm (None), gc_percent, length, ... }
    """
    if not result or "error" in result:
        return {
            "status": "ERROR",
            "tool_status": "ERROR",
            "error": result.get("error", "unknown") if result else "no response",
        }

    primers = result.get("top3") or result.get("top_primers") or []
    if not primers:
        return {"status": "NO_PRIMER", "tool_status": "NO_PRIMER"}

    top = primers[0]
    rt  = result.get("stemloop_rt") or {}
    hd  = top.get("heterodimer_checks") or {}

    # Dimer risk: any_high_risk → HIGH, any_moderate_or_above → MEDIUM, else LOW
    if hd.get("any_high_risk"):
        dimer_risk = "HIGH"
    elif hd.get("any_moderate_or_above"):
        dimer_risk = "MEDIUM"
    else:
        dimer_risk = "LOW"

    return {
        "status":      "OK",
        "tool_status": "OK",
        "fwd_tm":      top.get("tm_full"),
        "fwd_gc":      top.get("gc_percent"),
        "fwd_len":     len(top.get("sequence", "")),
        "rt_tm":       rt.get("tm"),          # often None (RT Tm not exposed)
        "rt_gc":       rt.get("gc_percent"),
        "rt_len":      rt.get("length") or len(rt.get("overhang_dna", "")),
        "dimer_risk":  dimer_risk,
        "score":       top.get("total_score"),
    }


# ── Markdown renderer ────────────────────────────────────────────────────────

def _render_md(rows: list[dict], mirprimer_available: bool) -> str:
    lines = [
        "# Benchmark: Primer Designer vs. Reference Tools",
        "",
        "Generated by `benchmark/run_benchmark.py`.",
        "All in-silico metrics only — no wet-lab efficiency data included.",
        "",
        "## Chemistry & Comparison Limitations",
        "",
        "| Factor | This tool | miRprimer / miPrimer |",
        "|--------|-----------|----------------------|",
        "| RT method | Stem-loop (Chen 2005) | Stem-loop or random hex |",
        "| Tm model | SantaLucia 1998 + salt corr. | Varies by tool version |",
        "| MGB / LNA | Planned (Phase 7+) | Tool-specific |",
        "| Dimer check | SantaLucia ΔG | Not always reported |",
        "| Specificity | Blast + family Kwok-distance | Basic BLAST |",
        "",
        "> **Calibration note:** Published paper efficiencies are NOT valid calibration",
        "> targets (different primers, no failure cases). Self-generated wet-lab data",
        "> required. See `calibration/calibration_data_requirement.md`.",
        "",
    ]

    if not mirprimer_available:
        lines += [
            "## miRprimer/miPrimer Column",
            "",
            "miRprimer binary not configured (`MIRPRIMER_TOOL` env-var unset).",
            "Set it to enable side-by-side column. Results below show this tool only.",
            "",
        ]

    # Summary statistics
    ok_rows    = [r for r in rows if r["tool_status"] == "OK"]
    fail_rows  = [r for r in rows if r["tool_status"] != "OK"]
    n_total    = len(rows)
    success_rt = len(ok_rows) / n_total * 100 if n_total else 0

    fwd_tms = [r["fwd_tm"] for r in ok_rows if r.get("fwd_tm") is not None]
    fwd_gcs = [r["fwd_gc"] for r in ok_rows if r.get("fwd_gc") is not None]

    lines += [
        "## Summary Statistics",
        "",
        f"- **Total miRNAs:** {n_total}",
        f"- **Primer design success:** {len(ok_rows)}/{n_total} ({success_rt:.1f}%)",
        f"- **Failures / no candidate:** {len(fail_rows)}",
    ]

    if fwd_tms:
        lines.append(f"- **Forward Tm range:** {min(fwd_tms):.1f}–{max(fwd_tms):.1f} °C "
                     f"(mean {sum(fwd_tms)/len(fwd_tms):.1f} °C)")
    if fwd_gcs:
        lines.append(f"- **Forward GC range:** {min(fwd_gcs):.1f}–{max(fwd_gcs):.1f}%")

    dimer_counts = {}
    for r in ok_rows:
        k = r.get("dimer_risk", "—")
        dimer_counts[k] = dimer_counts.get(k, 0) + 1
    if dimer_counts:
        lines.append(f"- **Dimer risk distribution:** {dict(sorted(dimer_counts.items()))}")

    lines += ["", "## Per-miRNA Results", ""]

    headers = [
        "miRNA ID", "Length", "GC%",
        "Tool status", "Fwd Tm", "Fwd GC%", "Fwd len",
        "RT Tm", "RT len", "Dimer", "Score",
    ]
    sep = ["---"] * len(headers)
    lines.append("| " + " | ".join(headers) + " |")
    lines.append("| " + " | ".join(sep) + " |")

    for r in rows:
        def f(v, digits=1):
            return f"{v:.{digits}f}" if v is not None else "—"

        lines.append(
            f"| {r['id']} | {r['length']} | {r['gc_pct']} "
            f"| {r['tool_status']} | {f(r.get('fwd_tm'))} | {f(r.get('fwd_gc'))} "
            f"| {r.get('fwd_len', '—')} | {f(r.get('rt_tm'))} | {r.get('rt_len', '—')} "
            f"| {r.get('dimer_risk', '—')} | {f(r.get('score'), 3)} |"
        )

    if fail_rows:
        lines += ["", "## Failures", ""]
        for r in fail_rows:
            lines.append(f"- **{r['id']}**: {r.get('error', r['tool_status'])}")

    lines += [
        "",
        "## Speed",
        "",
        f"- Total wall-clock (API calls only): see run log",
        "",
        "## Interpretation",
        "",
        "- Rows with `NO_PRIMER` indicate no primer passed all filters (Tm/GC/dimer).",
        "  Relax constraints (`tm_min`/`tm_max`, `gc_min`/`gc_max`) to diagnose.",
        "- Dimer risk `HIGH` does not mean the design is wrong — it flags pairs that",
        "  need experimental verification.",
        "- Chemistry differences (MGB, LNA, DMSO) can shift Tm 2-10°C vs. this tool's",
        "  SantaLucia 1998 + von Ahsen Mg correction.",
    ]

    return "\n".join(lines) + "\n"


# ── Main ─────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(description="Run in-silico benchmark against panel.json")
    parser.add_argument("--base-url", default=os.getenv("PRIMER_DESIGNER_URL", BASE_URL))
    parser.add_argument("--out",      default=str(OUT_FILE))
    parser.add_argument("--delay",    type=float, default=0.1,
                        help="seconds between requests (default 0.1)")
    args = parser.parse_args()

    mirprimer_bin = os.getenv("MIRPRIMER_TOOL", "")
    mirprimer_available = bool(mirprimer_bin)

    # Health check
    try:
        hc = requests.get(f"{args.base_url}/api/health", timeout=5)
        hc.raise_for_status()
    except Exception as exc:
        print(f"ERROR: Cannot reach backend at {args.base_url}: {exc}", file=sys.stderr)
        sys.exit(1)

    panel = json.loads(PANEL_FILE.read_text())
    mirnas = panel["mirnas"]
    print(f"Running benchmark: {len(mirnas)} miRNAs -> {args.out}")

    rows = []
    for i, m in enumerate(mirnas, 1):
        print(f"  [{i:2d}/{len(mirnas)}] {m['id']} ...", end=" ", flush=True)
        t0  = time.perf_counter()
        res = _call_design(args.base_url, m["sequence"], m["id"])
        elapsed = time.perf_counter() - t0

        metrics = _extract_metrics(res)
        row = {
            "id":          m["id"],
            "length":      m["length"],
            "gc_pct":      m["gc_pct"],
            "elapsed_s":   round(elapsed, 3),
            "tool_status": metrics.get("status", "ERROR"),
            **metrics,
        }
        rows.append(row)
        print(f"{metrics.get('status', 'ERROR')}  ({elapsed:.2f}s)")

        if args.delay > 0:
            time.sleep(args.delay)

    md = _render_md(rows, mirprimer_available)
    Path(args.out).write_text(md, encoding="utf-8")
    print(f"\nWrote {args.out}")

    ok_count = sum(1 for r in rows if r["tool_status"] == "OK")
    print(f"Success rate: {ok_count}/{len(rows)} ({ok_count/len(rows)*100:.1f}%)")


if __name__ == "__main__":
    main()
